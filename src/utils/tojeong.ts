export function calcTojeongGwe(year: number, month: number, day: number) {
  const sang = ((year - 4) % 60 % 8) + 1    // 1-8
  const jung = ((month - 1) % 6) + 1         // 1-6
  const ha   = ((day - 1) % 6) + 1           // 1-6
  return { sang, jung, ha, gwe: sang * 36 + jung * 6 + ha }
}

export function getTojeongMonthly(sang: number, jung: number, ha: number) {
  const pattern = SCORE_PATTERNS[sang - 1]
  const modifier = ((jung + ha) % 3) - 1   // -1, 0, +1

  return Array.from({ length: 12 }, (_, i) => {
    const rawScore = pattern[i]
    const score    = Math.min(5, Math.max(1, rawScore + (i % 3 === 0 ? modifier : 0)))
    const textPool = MONTH_TEXT[score]
    const variant  = (sang + jung + ha + i) % textPool.length
    const lineIdx  = (sang + i) % textPool[variant].length
    return { month: i + 1, score, text: textPool[variant][lineIdx] }
  })
}

