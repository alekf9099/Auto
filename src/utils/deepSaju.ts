export function getDeepContent(stemIndex: number): DeepContent {
  const stem = STEMS[stemIndex]
  const data = DEEP[stemIndex] ?? DEEP[0]
  return {
    stemName: stem.ko,
    stemHanja: stem.hanja,
    element: ELEMENT_KO[stem.element],
    yinYang: stem.yinYang === 'yang' ? '양(陽)' : '음(陰)',
    ...data,
  }
}

export function getOhaengAnalysis(count: OhaengCount): string {
  const order = ['wood','fire','earth','metal','water'] as const
  const names: Record<string, string> = { wood:'목(木)', fire:'화(火)', earth:'토(土)', metal:'금(金)', water:'수(水)' }
  const c = count as unknown as Record<string, number>
  const sorted = (order as readonly string[]).slice().sort((a, b) => (c[b] ?? 0) - (c[a] ?? 0))
  const strongest = names[sorted[0]]
  const weakest   = names[sorted[sorted.length - 1]]
  const total = order.reduce((s, k) => s + (c[k] ?? 0), 0) || 1

  const pct = (k: string) => Math.round(((c[k] ?? 0) / total) * 100)
  const balance = Math.max(...(order as readonly string[]).map(k => pct(k))) - Math.min(...(order as readonly string[]).map(k => pct(k)))

  let verdict = ''
  if (balance <= 15) verdict = '오행이 고르게 분포된 균형 잡힌 사주입니다. 다양한 환경에 잘 적응하며 두루두루 능력을 발휘합니다.'
  else if (balance <= 30) verdict = `${strongest} 기운이 약간 강한 편이지만 전체적으로 균형 잡혀 있습니다. ${strongest}의 특성이 삶의 여러 면에서 나타납니다.`
  else verdict = `${strongest} 기운이 매우 강하고 ${weakest} 기운이 부족합니다. ${strongest}의 장점이 두드러지는 만큼 ${weakest} 기운을 보완하는 노력이 필요합니다.`

  const bars = (order as readonly string[]).map(k => `${names[k]} ${pct(k)}%`).join(' · ')
  return `${bars}\n\n${verdict}`
}

export function calcDeepSaju(birth: BirthInput) {
  const saju = calculateSaju(birth)
  const ohaeng = getOhaengCount(saju)
  const stemIdx = saju.dayPillar.stemIndex
  return { content: getDeepContent(stemIdx), ohaengText: getOhaengAnalysis(ohaeng), stemIdx, saju }
}
